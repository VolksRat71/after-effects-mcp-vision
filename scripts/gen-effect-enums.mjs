#!/usr/bin/env node
// Regenerates cep/host/effect-enums.jsx: every built-in effect's popup options.
//
// After Effects has no API that lists a popup's options, so the host op
// `effectEnums` applies each effect in a throwaway comp and steps every popup
// through its values, reading valueText. Run this with After Effects open on a
// SCRATCH project (it adds and removes a comp) and the host freshly loaded:
//
//   node scripts/gen-effect-enums.mjs [batchSize]
//
// Progress is kept in a sidecar JSON, so a crash or timeout resumes where it
// stopped instead of starting over.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'cep', 'host', 'effect-enums.jsx');
const progressFile = path.join(os.tmpdir(), 'ae-mcp-effect-enums.progress.json');
const batch = Number(process.argv[2] || 20);
const port = Number(process.env.AE_MCP_PORT || 8791);
const token = fs.readFileSync(path.join(os.homedir(), '.ae-mcp-vision', 'token'), 'utf8').trim();

async function probe(offset) {
  const res = await fetch(`http://127.0.0.1:${port}/mcp`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream' },
    // ae_query forwards its command to the host op of the same name.
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call',
      params: { name: 'ae_query', arguments: { command: 'effectEnums', offset, limit: batch } } }),
  });
  const r = (await res.json()).result;
  const text = r.content[0].text;
  if (r.isError) throw new Error(text);
  return JSON.parse(text);
}

const state = fs.existsSync(progressFile)
  ? JSON.parse(fs.readFileSync(progressFile, 'utf8'))
  : { next: 0, results: {}, skipped: [], aeVersion: null };

while (state.next !== null) {
  const t0 = Date.now();
  const r = await probe(state.next);
  Object.assign(state.results, r.results);
  state.skipped.push(...r.skipped);
  state.aeVersion = r.aeVersion;
  console.log(`effects ${r.offset}-${Math.min(r.total, r.offset + batch) - 1} of ${r.total}: ` +
    `${Object.keys(r.results).length} with popups, ${r.skipped.length} skipped, ${Date.now() - t0} ms`);
  state.next = r.next;
  fs.writeFileSync(progressFile, JSON.stringify(state));
}

// ExtendScript reads a BOM-less .jsx in the system encoding, so any non-ASCII
// label (a degree sign, an ellipsis) is written as a \\u escape instead.
const ascii = (json) => json.replace(/[\u007f-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);

// Keyed by PARAMETER matchName ("ADBE Stroke-0007"), which is unique across
// effects - that is what the host has in hand when it reads or sets a value.
const table = {};
for (const fx of Object.values(state.results)) {
  for (const [mn, p] of Object.entries(fx.params)) table[mn] = p.options;
}
const body = `/*
 * GENERATED by scripts/gen-effect-enums.mjs on After Effects ${state.aeVersion} - do not edit.
 * Popup options for built-in effect parameters, keyed by parameter matchName;
 * option N (1-based) is the value AE stores. AE has no API for this table.
 */
var __mcp_effectEnums = ${ascii(JSON.stringify(table, null, 1))};
`;
fs.writeFileSync(outFile, body);
fs.unlinkSync(progressFile);
console.log(`wrote ${outFile}: ${Object.keys(table).length} popup parameters from ${Object.keys(state.results).length} effects; ` +
  `${state.skipped.length} effects skipped`);
if (state.skipped.length) console.log(JSON.stringify(state.skipped, null, 1));
